/** Подпись слота (или само имя, если подписи нет). */
export function slotLabel(slot: string): string {
  return ICON_SLOT_LABELS[slot] || slot;
}

/** Поиск по подписи и английскому имени, без учёта регистра. */
export function slotMatches(slot: string, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return slotLabel(slot).toLowerCase().includes(q) || slot.toLowerCase().includes(q);
}
