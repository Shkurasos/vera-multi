/**
 * Ключ для сравнения жанров и поиска по ним.
 *
 * Повторяет правило серверного `music-genres.normalizeKey` — не таблицу
 * синонимов (её клиенту незачем: приводит к канону сервер), а только нормализацию
 * написания: нижний регистр, «ё»→«е» и ничего, кроме букв и цифр. Без этого
 * «Рок» и «rock» сравнивались бы как разные строки, и поиск по жанру в форме
 * вёл бы себя иначе, чем на сервере.
 */
export function normalizeKey(value: string | null | undefined): string {
  return String(value == null ? '' : value)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/gi, '');
}