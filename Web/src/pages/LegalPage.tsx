export default function LegalPage({ kind }: { kind: LegalKind }) {
  const { theme } = useThemeStore();
  const navHeight = useUiPrefsStore((s) => s.navHeight);
  const blocks = useMemo(() => (kind === 'privacy' ? PRIVACY : TERMS), [kind]);
  const title = kind === 'privacy' ? 'Политика конфиденциальности' : 'Правила использования мессенджера';

  return (
    <Box sx={{ minHeight: '100vh', bgcolor: theme.bg, color: theme.text, overflowY: 'auto' }}>
      <Box sx={{ maxWidth: 820, mx: 'auto', px: 2, pt: 2, pb: `calc(${navHeight}px + 32px)` }}>
        <Stack direction="row" alignItems="center" spacing={1} sx={{ mb: 2 }}>
          <PageBackButton />
          <Typography variant="h5" sx={{ fontWeight: 700 }}>{title}</Typography>
        </Stack>

        <Typography variant="body2" sx={{ color: theme.textSec, mb: 2 }}>
          Последнее обновление: {LAST_UPDATED}
        </Typography>

        <Paper sx={{ p: { xs: 2, sm: 3 }, bgcolor: theme.bgHeader, color: theme.text, borderRadius: 2, border: `1px solid ${theme.border}` }}>
          <Stack spacing={2.5}>
            {blocks.map((block, i) => (
              <Box key={i}>
                <Typography variant="subtitle1" sx={{ fontWeight: 700, mb: 1 }}>{block.h}</Typography>
                <Stack spacing={1}>
                  {block.p.map((para, j) =>
                    Array.isArray(para) ? (
                      <Box component="ul" key={j} sx={{ m: 0, pl: 3 }}>
                        {para.map((li, k) => (
                          <Typography component="li" variant="body2" key={k} sx={{ color: theme.text, mb: 0.5, lineHeight: 1.6 }}>
                            {li}
                          </Typography>
                        ))}
                      </Box>
                    ) : (
                      <Typography variant="body2" key={j} sx={{ color: theme.text, lineHeight: 1.6 }}>
                        {para}
                      </Typography>
                    )
                  )}
                </Stack>
                {i < blocks.length - 1 && <Divider sx={{ mt: 2.5, borderColor: theme.border }} />}
              </Box>
            ))}
          </Stack>
        </Paper>
      </Box>
    </Box>
  );
}

