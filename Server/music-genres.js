/**
 * Привести произвольную строку к виду, по которому ищем синоним.
 *
 * Убираем всё, что не буква и не цифра, плюс сводим «ё» к «е». Так «R&B»,
 * «R&B» и «R&B» схлопываются в одно, а «рок-н-ролл» ищется как «рокнролл».
 * Без этого «Хип-хоп» и «хип хоп» были бы разными жанрами — а это ровно та
 * беда, ради которой модуль и написан.
 */
function normalizeKey(value) {
  return String(value == null ? '' : value)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/gi, '');
}

/**
 * Канонический жанр или null, если такого жанра нет.
 *
 * Сначала точное совпадение с каноном (самый частый случай — клиент прислал
 * значение из списка), потом синонимы. Регистр и оформление не важны.
 */
function normalizeGenre(value) {
  const key = normalizeKey(value);
  if (!key) return null;
  const exact = GENRES.find((g) => normalizeKey(g) === key);
  if (exact) return exact;
  return ALIASES[key] || null;
}

/**
 * Тот же жанр в каноне для записи, уже лежащей в базе.
 *
 * Нужна для старых записей: их жанр писали свободным текстом, и без приведения
 * «Rock» остался бы отдельным жанром рядом с «Рок». Незнакомое не выбрасываем,
 * а оставляем как было: удалять чужое описание нельзя, пусть даже оно не из
 * списка — так его хотя бы видно в поиске.
 */
function canonicalOrKeep(value) {
  const clean = String(value == null ? '' : value).trim().slice(0, 60);
  if (!clean) return null;
  return normalizeGenre(clean) || clean;
}

